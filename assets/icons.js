export function icon(name, size = 24, { strokeWidth = 2 } = {}) {
  const shapes = nodes[name];
  if (!shapes) throw new Error(`Icône inconnue : ${name}`);
  const inner = shapes
    .map(([tag, attrs]) =>
      `<${tag} ${Object.entries(attrs)
        .filter(([key]) => key !== "key")
        .map(([key, value]) => `${key}="${value}"`)
        .join(" ")} />`,
    )
    .join("");
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ` +
    `viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" ` +
    `stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" class="icon icon-${name}">${inner}</svg>`
  );
}
